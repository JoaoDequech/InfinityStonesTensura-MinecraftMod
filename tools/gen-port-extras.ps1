# Generates src/main/resources/data/infinity/stone_trees/extras/port/<stone>.json overrides (port-originals).
$ErrorActionPreference = 'Stop'
$repo = 'D:\InfinityTensura\infinity-port'
$trees = "$repo\src\main\resources\data\infinity\stone_trees"
$orig = Join-Path ([Environment]::GetFolderPath("Desktop")) "infinity-7.2-neoforge-1.21.1-working/data/infinity/palladium/power"
$map = @{mind='mind_stone';power='power_stone_passive';space='space_stone';reality='reality_stone';soul='soul_stone';time='time_stone'}
# node id -> new activation (in_bar forced true)
$over = @{
  mind = @{ 'flight_toggle' = 'toggle' }
  power = @{ 'radiation_texture_toggle' = 'toggle'; 'size_toggle' = 'press' }
  time = @{ 'screen_toggle' = 'toggle'; 'daylight_cycle_toggle' = 'toggle'; 'reset_time_speed' = 'press' }
  reality = @{ 'size_toggle' = 'press' }
  space = @{}
  soul = @{}
}
$hidden = @{ space = @('tick'); power = @('tick'); time = @('tick'); mind=@(); reality=@(); soul=@() }
New-Item -ItemType Directory -Force "$trees\extras\port" | Out-Null
foreach ($s in $map.Keys) {
  $t = Get-Content "$trees\$s.json" -Raw | ConvertFrom-Json
  $nodes = New-Object System.Collections.ArrayList
  foreach ($n in $t.nodes) {
    if ($over[$s].ContainsKey($n.id)) {
      $c = $n.PSObject.Copy()
      $c.activation = $over[$s][$n.id]
      $c.in_bar = $true
      $c.first_tick_commands = @(); $c.commands = @(); $c.last_tick_commands = @()
      [void]$nodes.Add($c)
    }
  }
  $j = Get-Content "$orig\$($map[$s]).json" -Raw | ConvertFrom-Json
  foreach ($h in $hidden[$s]) {
    $a = $j.abilities.$h
    $first = @($a.first_tick_commands | Where-Object { $_ }); $cmds = @($a.commands | Where-Object { $_ }); $last = @($a.last_tick_commands | Where-Object { $_ })
    $node = [ordered]@{ id = "hidden_$h"; original_type = 'palladium:command'; title = "hidden_$h"; description = ''; icon = $null; cost = $null;
      parents = @(); requires_stones = @(); activation = 'passive'; cooldown_ticks = 0; in_tree = $false; in_bar = $false; gui_position = $null;
      commands = $cmds; first_tick_commands = $first; last_tick_commands = $last; raw = $a }
    [void]$nodes.Add([pscustomobject]$node)
  }
  $out = [ordered]@{ '_comment' = 'port-originals: overrides of original nodes (same id) and hidden original helpers. Generated by tools/gen-port-extras.ps1 + hand-written new abilities.'; nodes = $nodes }
  # generated part goes to extras/port/<stone>.json; hand-written new abilities live in extras/port/new/<stone>.json
  [IO.File]::WriteAllText("$trees\extras\port\$s.json", ($out | ConvertTo-Json -Depth 40), (New-Object System.Text.UTF8Encoding $false))
  "$s : $($nodes.Count) nodes"
}
